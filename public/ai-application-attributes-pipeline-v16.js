(() => {
  const config = window.__AI_APPLICATION_ATTRIBUTES_PIPELINE_CONFIG__;
  if (!config || !Array.isArray(config.stages)) return;

  const byKey = Object.fromEntries(config.stages.map((stage) => [stage.outKey, stage]));
  const insertBefore = (source, marker, addition) => {
    if (!source || source.includes(addition.trim())) return source;
    return source.includes(marker)
      ? source.replace(marker, `${addition}\n\n${marker}`)
      : `${source}\n\n${addition}`;
  };

  const extractorRule = `ИСТОРИЯ ОБЪЕКТА НЕ РАВНА ИНТЕРЕСУ К НОВОСТРОЙКАМ

Не выбирай «Новостройки» только на основании прошлого или юридической истории продаваемого объекта:

- текущий собственник когда-то покупал объект у застройщика или по ДДУ;
- объект раньше продавался как новостройка;
- дом недавно сдан, а ключи уже получены;
- ремонт выполнен застройщиком;
- объект первоначально приобретался у девелопера.

Если объект уже оформлен в собственность и продаётся собственником как готовый объект, прошлый ДДУ или покупка у застройщика сами по себе не подтверждают интерес клиента к новостройкам.

Без прямого вопроса сотрудника выбирай «Новостройки» только по признакам ТЕКУЩЕЙ рассматриваемой клиентом первичной сделки: клиент покупает у застройщика, по ДДУ или переуступке права требования; объект ещё строится или не сдан; обсуждается текущая бронь, эскроу либо срок сдачи приобретаемого объекта.

Реплики агента об истории объекта используй только как дополнительный контекст, когда интерес клиента к первичному рынку уже подтверждён другим evidence.

NEGATIVE EXAMPLES

Агент: «Квартира куплена собственником по ДДУ в 2021 году, сейчас собственность оформлена». Клиент не говорит о первичном рынке. Ответ не содержит «Новостройки».

Агент: «Ремонт от застройщика, ключи получили год назад». Клиент интересуется только этой готовой квартирой. Ответ не содержит «Новостройки».

Оператор: «Новостройки рассматриваете?» Клиент: «Нет, только вторичку». Поздний рассказ агента о прошлом ДДУ продавца не отменяет отказ. Ответ не содержит «Новостройки».

POSITIVE EXAMPLES

Клиент: «Рассматриваю также несданные квартиры от застройщика». Ответ содержит «Новостройки».

Клиент: «Звоню по переуступке, когда сдаётся корпус?» Ответ содержит «Новостройки».`;

  const judgeRule = `СЕМАНТИЧЕСКАЯ РОЛЬ EVIDENCE ДЛЯ НОВОСТРОЕК

Evidence для «Интересует» должно доказывать потребность или текущий интерес клиента.

Не используй как самостоятельное evidence реплики агента, которые описывают только историю приобретения продавцом, правоустанавливающие документы продавца, прошлый ДДУ, прошлую покупку у застройщика, характеристики объекта, происхождение ремонта или получение ключей текущим собственником. Такие данные не являются потребностью клиента.

Контекст без прямого подтверждения подходит только тогда, когда он однозначно относится к ТЕКУЩЕЙ покупке клиента на первичном рынке: покупка у застройщика, текущий ДДУ, переуступка права требования, строящийся или несданный приобретаемый объект, текущая бронь, эскроу либо срок сдачи приобретаемого объекта.

reason_code newbuild_from_context используй только для такого текущего интереса клиента. Не используй его из-за фразы «Собственник покупал по ДДУ».

Если есть direct_confirmation или soft_confirmation клиента, это основное основание. Не добавляй ложное evidence и второй reason_code только ради упоминания истории объекта.

Проверочные примеры:

- прошлый ДДУ продавца при оформленной собственности без интереса клиента к первичке — «Новостройки» не подтверждены;
- ремонт от застройщика и полученные год назад ключи готовой квартиры — «Новостройки» не подтверждены;
- прямой отказ «Нет, только вторичку» имеет приоритет над рассказом агента о прошлом ДДУ;
- «Рассматриваю также несданные квартиры от застройщика» подтверждает «Новостройки»;
- «Звоню по переуступке, когда сдаётся корпус?» подтверждает «Новостройки».`;

  if (byKey.interest_extractor) {
    byKey.interest_extractor.prompt = insertBefore(
      byKey.interest_extractor.prompt,
      "ПЕРЕД ОТВЕТОМ ПРОВЕРЬ",
      extractorRule,
    );
    byKey.interest_extractor.promptVersion = 16;
  }

  if (byKey.interest_judge) {
    byKey.interest_judge.prompt = insertBefore(
      byKey.interest_judge.prompt,
      "ФОРМАТ",
      judgeRule,
    );
    byKey.interest_judge.promptVersion = 16;
  }

  if (byKey.crm_attributes_result) {
    byKey.crm_attributes_result.runtimeType = "deterministic";
    byKey.crm_attributes_result.actualExecutor = "code";
    byKey.crm_attributes_result.sourceOutKey = "attributes_quality_gate";
    byKey.crm_attributes_result.contractId = "crm_attributes_result";
    byKey.crm_attributes_result.contractVersion = "v1";
  }

  config.revision = 16;
})();
